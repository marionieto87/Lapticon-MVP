export function formatDate(iso: string, lang: Lang) {
  const [y, m, d] = iso.slice(0, 10).split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d)).toLocaleDateString(lang === "en" ? "en-CA" : "es-CO", {
    day: "numeric",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  });
}

export function formatMoney(n: number, currency: string, lang: Lang) {
  return new Intl.NumberFormat(lang === "en" ? "en-CA" : "es-CO", {
    style: "currency",
    currency,
    maximumFractionDigits: currency === "COP" ? 0 : 2,
  }).format(n);
}
