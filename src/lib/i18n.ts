export type Level = "new" | "bronze" | "silver" | "gold";

// Requester level from the number of requests delivered through Lapticon.
export function levelFor(delivered: number): Level {
  if (delivered >= 10) return "gold";
  if (delivered >= 3) return "silver";
  if (delivered >= 1) return "bronze";
  return "new";
}

